def load_fonts(font_dir: Path = FONT_DIR) -> dict[str, str]:
    out = {}
    for role in ROLES:
        path = font_dir / f"{role.symbol}.c"
        if path.is_file():
            out[role.symbol] = path.read_text(encoding="utf-8")
    return out


def coverage_errors(inv: Inventory, parsed: dict[str, ParsedFont]) -> list[str]:
    errors = []
    for role in ROLES:
        pf = parsed.get(role.symbol)
        if pf is None:
            continue
        covered = pf.coverage()
        for cp in sorted(inv.required(role) - covered):
            ch = chr(cp).encode("ascii", "backslashreplace").decode("ascii")
            errors.append(f"{role.symbol} ({role.role}) lacks {u_label(cp)} '{ch}' used by "
                          f"{inv.origin(cp)}: regenerate with tools/vocab_fonts.py generate")
    return errors


IPA_FONT = "vocab_font_ipa_18"       # F_IPA: bank IPA line, double-storey a (ss13)
EXAMPLE_FONT = "vocab_font_en_18"    # F_EN_XS: example sentences, default single-storey a
A_SHAPE_MIN_PIXELS = 8


def shape_errors(parsed: dict[str, ParsedFont]) -> list[str]:
    """Spec 11.3 and the orchestrator's split: F_IPA draws U+0061 visibly unlike U+0251,
    while F_EN_XS keeps Andika's default single-storey a - the same outline as Andika's
    U+0251, so the two 18 px bitmaps (same source, size and hinting) are identical."""
    ipa, example = parsed.get(IPA_FONT), parsed.get(EXAMPLE_FONT)
    if ipa is None or example is None or not (ipa.lookup(0x61) and ipa.lookup(0x251)
                                              and example.lookup(0x61)):
        return []  # missing fonts or glyphs are reported by the structure/coverage checks
    errors = []
    apart = glyph_distance(ipa, 0x61, 0x251)
    if apart < A_SHAPE_MIN_PIXELS:
        errors.append(f"{IPA_FONT} (F_IPA): U+0061 and U+0251 differ in only {apart} pixels; "
                      "IPA needs the double-storey a")
    drift = glyph_distance(example, 0x61, 0x251, ipa)
    if drift:
        errors.append(f"{EXAMPLE_FONT} (F_EN_XS): U+0061 differs from Andika's single-storey a "
                      f"in {drift} pixels; example sentences keep the default a")
    return errors


def check(sources: dict[str, str], fonts: dict[str, str], inventory_text: str | None,
          extra_bank: tuple[dict[str, object], ...] = (),
          font_dir: Path | None = FONT_DIR) -> tuple[list[str], dict[str, ParsedFont]]:
    """All problems of the generated fonts against the sources (empty = PASS)."""
    inv = build_inventory(sources, extra_bank)
    errors = list(inv.errors)
    parsed: dict[str, ParsedFont] = {}
    for role in ROLES:
        text = fonts.get(role.symbol)
        if text is None:
            errors.append(f"missing assets/fonts/vocab/{role.symbol}.c")
            continue
        try:
            pf = parse_font_c(text)
        except FontToolError as exc:
            errors.append(f"{role.symbol}: {exc}")
            continue
        parsed[role.symbol] = pf
        errors += [f"{role.symbol}: {msg}" for msg in structure_errors(pf, role.symbol)]
    errors += coverage_errors(inv, parsed)
    errors += shape_errors(parsed)

    # The committed inventory records what each font was generated from (code points and
    # the LF-normalized SHA-256 of the file): a hand-edited font fails here.
    try:
        recorded = json.loads(inventory_text) if inventory_text is not None else None
    except json.JSONDecodeError as exc:
        recorded = None
        errors.append(f"vocab_fonts_inventory.json: {exc}")
    if recorded is None:
        errors.append("missing or unreadable assets/fonts/vocab/vocab_fonts_inventory.json")
    else:
        for role in ROLES:
            rec = recorded.get("fonts", {}).get(role.symbol)
            pf = parsed.get(role.symbol)
            if rec is None or pf is None:
                errors.append(f"{role.symbol}: not recorded in the inventory")
                continue
            if rec.get("c_sha256") != text_sha256(fonts[role.symbol]):
                errors.append(f"{role.symbol}: file differs from the recorded generation")
            listed = {int(tok[2:], 16) for tok in rec.get("codepoints", "").split()}
            if listed != pf.coverage():
                errors.append(f"{role.symbol}: inventory code points differ from the font cmaps")
            if (rec.get("size_px"), rec.get("bpp"), rec.get("line_height"), rec.get("base_line")) != (
                    role.size, 4, pf.line_height, pf.base_line):
                errors.append(f"{role.symbol}: inventory size/bpp/line metrics differ from the font")
    if font_dir is not None:
        for name, (_, digest) in LICENSES.items():
            path = font_dir / name
            if not path.is_file() or hashlib.sha256(
                    norm_text(path.read_text(encoding="utf-8")).encode("utf-8")).hexdigest() != digest:
                errors.append(f"assets/fonts/vocab/{name}: missing or not the pinned license text")
    return errors, parsed


# Negative self-test cases: each must make the check fail, naming the injected code point.
SELF_TEST_CASES = (
    ("an uncovered CJK UI string", {"main/vocab_selftest.c": 'const char *s = "\\u9F98";'},
     (), "U+9F98"),
    ("an uncovered IPA symbol in the bank", {},
     ({"uid": 65000, "text": "test", "ipa": "/t\u025at/", "zh": "\u6d4b"},), "U+025A"),
    ("non-ASCII English bank text", {},
     ({"uid": 65001, "text": "caf\u00e9", "zh": "\u6d4b"},), "U+00E9"),
    ("an unknown LVGL symbol", {"main/vocab_selftest.c": 'const char *s = "\\xEF\\xA3\\xBF";'},
     (), "U+F8FF"),
)


SHAPE_SELF_TESTS = 2  # F_EN_XS with the double-storey a; F_IPA whose a looks like U+0251


def self_test(sources: dict[str, str], fonts: dict[str, str], inventory_text: str | None) -> list[str]:
    """Returns failures of the negative self-test (empty = every injection was caught)."""
    failures = []
    for name, extra_sources, extra_bank, label in SELF_TEST_CASES:
        injected = dict(sources)
        injected.update(extra_sources)
        errors, _ = check(injected, fonts, inventory_text, extra_bank, font_dir=None)
        if not any(label in err for err in errors):
            failures.append(f"self-test: {name} ({label}) was not detected")
    # a-shape intent: swapped shapes must be reported for the role that carries them.
    try:
        ipa, example = parse_font_c(fonts[IPA_FONT]), parse_font_c(fonts[EXAMPLE_FONT])
    except (KeyError, FontToolError):
        return failures  # missing/broken fonts already fail the main check
    if not any(EXAMPLE_FONT in e for e in shape_errors({IPA_FONT: ipa, EXAMPLE_FONT: ipa})):
        failures.append("self-test: F_EN_XS drawn with the double-storey a was not detected")
    glyphs = list(ipa.glyphs)
    glyphs[ipa.lookup(0x61)] = glyphs[ipa.lookup(0x251)]
    alpha_a = replace(ipa, glyphs=glyphs)
    if not any(IPA_FONT in e for e in shape_errors({IPA_FONT: alpha_a, EXAMPLE_FONT: example})):
        failures.append("self-test: F_IPA with an alpha-shaped a was not detected")
    return failures


def run_check() -> int:
    sources = source_files()
    fonts = load_fonts()
    inventory_text = INVENTORY_PATH.read_text(encoding="utf-8") if INVENTORY_PATH.is_file() else None
    errors, parsed = check(sources, fonts, inventory_text)
    header = FONTS_HEADER.read_text(encoding="utf-8") if FONTS_HEADER.is_file() else ""
    if not re.search(r"(?m)^#define\s+VOCAB_FONTS_PLACEHOLDER\s+0\b", header):
        errors.append("main/vocab_fonts.h: VOCAB_FONTS_PLACEHOLDER must be 0 with generated fonts")
    for role in ROLES:
        if f"LV_FONT_DECLARE({role.symbol})" not in header:
            errors.append(f"main/vocab_fonts.h: missing LV_FONT_DECLARE({role.symbol})")
    errors += self_test(sources, fonts, inventory_text)
    if errors:
        for err in errors:
            print(f"vocab_fonts.py --check: ERROR: {err}", file=sys.stderr)
        print(f"vocab_fonts.py --check: FAIL ({len(errors)} problem(s))", file=sys.stderr)
        return 1
    inv = build_inventory(sources)
    total = sum(pf.flash_bytes() for pf in parsed.values())
    print(f"vocab_fonts.py --check: PASS ({len(sources)} sources, {inv.bank_entries} bank entries, "
          f"{len(inv.groups['cjk'])} CJK-role and {len(inv.groups['ipa'])} IPA code points; "
          f"{len(parsed)} fonts, about {total // 1024} KiB; self-test caught "
          f"{len(SELF_TEST_CASES) + SHAPE_SELF_TESTS} injections)")
    return 0


