class FontToolError(Exception):
    """A problem that stops generation or the check."""


def u_label(cp: int) -> str:
    return f"U+{cp:04X}"


def norm_text(text: str) -> str:
    return text.replace("\r\n", "\n")


def text_sha256(text: str) -> str:
    """SHA-256 of a text file with LF line endings (stable under git autocrlf)."""
    return hashlib.sha256(norm_text(text).encode("utf-8")).hexdigest()


# ---------------------------------------------------------------------------------------
# C source scanning: string literals and bank entries (standard library only)
# ---------------------------------------------------------------------------------------

_TOKEN_RE = re.compile(
    r'//[^\n]*|/\*.*?\*/|"(?:[^"\\\n]|\\.)*"|\'(?:[^\'\\\n]|\\.)*\'', re.S)
_STRING_RE = re.compile(r'"((?:[^"\\\n]|\\.)*)"')
_ESCAPES = {"n": 10, "t": 9, "r": 13, "a": 7, "b": 8, "f": 12, "v": 11, "\\": 92,
            "'": 39, '"': 34, "?": 63}


def normalize_c(src: str) -> str:
    """Comments removed (literals kept), CRLF -> LF, macro continuation lines joined."""
    def repl(m: re.Match) -> str:
        tok = m.group(0)
        if tok.startswith("//"):
            return ""
        if tok.startswith("/*"):
            return " "
        return tok
    code = _TOKEN_RE.sub(repl, norm_text(src))
    return re.sub(r"\\\n", " ", code)


def decode_c_string(body: str) -> str:
    """Decodes the body of a C string literal (UTF-8 source; \\x, \\u, octal escapes)."""
    out = bytearray()
    i = 0
    while i < len(body):
        ch = body[i]
        if ch != "\\":
            out += ch.encode("utf-8")
            i += 1
            continue
        nxt = body[i + 1]
        if nxt == "x":
            j = i + 2
            while j < len(body) and body[j] in "0123456789abcdefABCDEF":
                j += 1
            out.append(int(body[i + 2:j], 16) & 0xFF)
            i = j
        elif nxt in "uU":
            width = 4 if nxt == "u" else 8
            out += chr(int(body[i + 2:i + 2 + width], 16)).encode("utf-8")
            i += 2 + width
        elif nxt in "01234567":
            j = i + 1
            while j < len(body) and j < i + 4 and body[j] in "01234567":
                j += 1
            out.append(int(body[i + 1:j], 8) & 0xFF)
            i = j
        else:
            out.append(_ESCAPES[nxt])
            i += 2
    try:
        return out.decode("utf-8")
    except UnicodeDecodeError as exc:
        raise FontToolError(f"string literal is not valid UTF-8: \"{body}\"") from exc


def scan_literals(code: str) -> list[tuple[int, str]]:
    """(offset, decoded value) of every string literal of normalized code."""
    out = []
    for m in _TOKEN_RE.finditer(code):
        if m.group(0).startswith('"'):
            out.append((m.start(), decode_c_string(m.group(0)[1:-1])))
    return out


def _match_literal(text: str, i: int) -> int:
    quote = text[i]
    m = re.compile(r'"(?:[^"\\]|\\.)*"' if quote == '"' else r"'(?:[^'\\]|\\.)*'").match(text, i)
    if not m:
        raise FontToolError("unterminated literal in the bank source")
    return m.end()


def _balanced(code: str, open_at: int, opener: str, closer: str) -> int:
    """Index just after the bracket matching code[open_at] (literals respected)."""
    depth = 0
    i = open_at
    while i < len(code):
        ch = code[i]
        if ch in "\"'":
            i = _match_literal(code, i)
            continue
        if ch == opener:
            depth += 1
        elif ch == closer:
            depth -= 1
            if depth == 0:
                return i + 1
        i += 1
    raise FontToolError("unbalanced brackets in the bank source")


def _split_args(text: str) -> list[str]:
    args, cur, depth, i = [], [], 0, 0
    while i < len(text):
        ch = text[i]
        if ch in "\"'":
            j = _match_literal(text, i)
            cur.append(text[i:j])
            i = j
            continue
        if ch in "([{":
            depth += 1
        elif ch in ")]}":
            depth -= 1
        if ch == "," and depth == 0:
            args.append("".join(cur).strip())
            cur = []
        else:
            cur.append(ch)
        i += 1
    args.append("".join(cur).strip())
    return args


def _field_value(arg: str) -> object:
    arg = arg.strip()
    while arg.startswith("(") and arg.endswith(")"):
        arg = arg[1:-1].strip()
    if arg in ("NULL", "((void *)0)"):
        return None
    if re.fullmatch(r"-?(0x[0-9a-fA-F]+|\d+)u?", arg):
        return int(arg.rstrip("u"), 0)
    parts = _STRING_RE.findall(arg)
    if not parts or _STRING_RE.sub("", arg).strip():
        raise FontToolError(f"unsupported bank field value: {arg!r}")
    return "".join(decode_c_string(p) for p in parts)


def parse_bank(code: str) -> tuple[list[dict[str, object]], list[tuple[int, int]]]:
    """Bank entries of normalized main/vocab_bank.c and the spans of their initializers.

    Supports entry macros whose body assigns fields from parameters (`.text = (text_)`, the
    current bank) and plain designated initializers (`{ .uid = 101, .text = "apple" }`).
    """
    macros: dict[str, dict[str, int]] = {}
    for m in re.finditer(r"(?m)^[ \t]*#[ \t]*define[ \t]+(\w+)\(([^)]*)\)(.*)$", code):
        params = [p.strip() for p in m.group(2).split(",")]
        mapping = {}
        for fm in re.finditer(r"\.(\w+)\s*=\s*\(?\s*(\w+)\s*\)?", m.group(3)):
            if fm.group(2) in params:
                mapping[fm.group(1)] = params.index(fm.group(2))
        if "uid" in mapping and "text" in mapping:
            macros[m.group(1)] = mapping
    body = re.sub(r"(?m)^[ \t]*#.*$", lambda m: " " * len(m.group(0)), code)
    entries: list[tuple[int, dict[str, object]]] = []
    spans: list[tuple[int, int]] = []
    for name, mapping in macros.items():
        for m in re.finditer(rf"\b{re.escape(name)}\s*\(", body):
            end = _balanced(body, m.end() - 1, "(", ")")
            args = _split_args(body[m.end():end - 1])
            entry = {fld: _field_value(args[idx]) for fld, idx in mapping.items()}
            entries.append((m.start(), entry))
            spans.append((m.start(), end))
    for m in re.finditer(r"\{\s*\.uid\s*=", body):
        end = _balanced(body, m.start(), "{", "}")
        entry = {}
        for part in _split_args(body[m.start() + 1:end - 1]):
            fm = re.match(r"\.(\w+)\s*=\s*(.*)$", part, re.S)
            if fm:
                entry[fm.group(1)] = _field_value(fm.group(2))
        entries.append((m.start(), entry))
        spans.append((m.start(), end))
    entries.sort(key=lambda e: e[0])
    return [e for _, e in entries], spans


