FORMAT0_TINY = "LV_FONT_FMT_TXT_CMAP_FORMAT0_TINY"
SPARSE_TINY = "LV_FONT_FMT_TXT_CMAP_SPARSE_TINY"


@dataclass
class Glyph:
    bitmap_index: int
    adv_w: int     # 1/16 px
    box_w: int
    box_h: int
    ofs_x: int
    ofs_y: int     # bottom of the box relative to the baseline (up is positive)


@dataclass
class Cmap:
    range_start: int
    range_length: int
    glyph_id_start: int
    unicode_list: list[int] | None
    list_length: int
    kind: str


@dataclass
class ParsedFont:
    symbol: str
    line_height: int
    base_line: int
    bpp: int
    bitmap_format: str
    stride: int
    cmap_num: int
    kern: str
    bitmap: bytes
    glyphs: list[Glyph]
    cmaps: list[Cmap]
    includes_lvgl: bool
    generated: bool

    def lookup(self, cp: int) -> int:
        """Glyph id exactly as LVGL 9.5 get_glyph_dsc_id() resolves it (0 = missing)."""
        if cp == 0:
            return 0
        for c in self.cmaps:
            rcp = cp - c.range_start
            if rcp < 0 or rcp >= c.range_length:
                continue
            if c.kind == FORMAT0_TINY:
                return c.glyph_id_start + rcp
            if c.kind == SPARSE_TINY and c.unicode_list is not None:
                lo, hi = 0, len(c.unicode_list)
                while lo < hi:
                    mid = (lo + hi) // 2
                    if c.unicode_list[mid] < rcp:
                        lo = mid + 1
                    else:
                        hi = mid
                if lo < len(c.unicode_list) and c.unicode_list[lo] == rcp:
                    return c.glyph_id_start + lo
            return 0
        return 0

    def coverage(self) -> set[int]:
        out = set()
        for c in self.cmaps:
            if c.kind == FORMAT0_TINY:
                out.update(range(c.range_start, c.range_start + c.range_length))
            elif c.unicode_list is not None:
                out.update(c.range_start + r for r in c.unicode_list)
        return {cp for cp in out if self.lookup(cp)}

    def decode(self, gid: int) -> list[list[int]]:
        """4-bit pixel rows of a glyph, read like LVGL's PLAIN 4 bpp decoder (stride 0)."""
        g = self.glyphs[gid]
        rows = []
        k = 0
        for _ in range(g.box_h):
            row = []
            for _ in range(g.box_w):
                byte = self.bitmap[g.bitmap_index + (k >> 1)]
                row.append(byte >> 4 if k % 2 == 0 else byte & 0x0F)
                k += 1
            rows.append(row)
        return rows

    def flash_bytes(self) -> int:
        """Estimated flash of the font data (bitmaps, descriptors, cmaps, font structs)."""
        lists = sum(2 * len(c.unicode_list or ()) for c in self.cmaps)
        return len(self.bitmap) + 8 * len(self.glyphs) + lists + 24 * len(self.cmaps) + 24 + 48


def _strip_block_comments(text: str) -> str:
    return re.sub(r"/\*.*?\*/", " ", text, flags=re.S)


def parse_font_c(text: str) -> ParsedFont:
    src = norm_text(text)
    code = _strip_block_comments(re.sub(r"(?m)//[^\n]*", "", src))

    def need(pattern: str, what: str) -> re.Match:
        m = re.search(pattern, code, re.S)
        if not m:
            raise FontToolError(f"cannot find {what}")
        return m

    bitmap_m = need(r"glyph_bitmap\[\]\s*=\s*\{(.*?)\};", "glyph_bitmap[]")
    bitmap = bytes(int(v, 16) for v in re.findall(r"0x([0-9a-fA-F]{1,2})\b", bitmap_m.group(1)))
    dsc_m = need(r"glyph_dsc\[\]\s*=\s*\{(.*?)\};", "glyph_dsc[]")
    glyphs = [Glyph(*(int(v) for v in g)) for g in re.findall(
        r"\{\s*\.bitmap_index\s*=\s*(\d+),\s*\.adv_w\s*=\s*(\d+),\s*\.box_w\s*=\s*(\d+),"
        r"\s*\.box_h\s*=\s*(\d+),\s*\.ofs_x\s*=\s*(-?\d+),\s*\.ofs_y\s*=\s*(-?\d+)\s*\}",
        dsc_m.group(1))]
    lists = {name: [int(v, 16) for v in re.findall(r"0x([0-9a-fA-F]+)", body)]
             for name, body in re.findall(
                 r"static\s+const\s+uint16_t\s+(\w+)\[\]\s*=\s*\{(.*?)\};", code, re.S)}
    cmap_m = need(r"cmaps\[\]\s*=\s*\{(.*?)\n\};", "cmaps[]")
    cmaps = []
    for m in re.finditer(
            r"\.range_start\s*=\s*(\d+),\s*\.range_length\s*=\s*(\d+),\s*\.glyph_id_start\s*=\s*(\d+),"
            r"\s*\.unicode_list\s*=\s*(\w+),\s*\.glyph_id_ofs_list\s*=\s*(\w+),"
            r"\s*\.list_length\s*=\s*(\d+),\s*\.type\s*=\s*(\w+)", cmap_m.group(1)):
        ulist = None if m.group(4) == "NULL" else lists.get(m.group(4))
        if m.group(4) != "NULL" and ulist is None:
            raise FontToolError(f"unknown unicode list {m.group(4)}")
        if m.group(5) != "NULL":
            raise FontToolError("glyph_id_ofs_list must be NULL (TINY cmaps only)")
        cmaps.append(Cmap(int(m.group(1)), int(m.group(2)), int(m.group(3)), ulist,
                          int(m.group(6)), m.group(7)))

    def field_of(name: str, pattern: str = r"(-?\w+)") -> str:
        return need(rf"\.{name}\s*=\s*{pattern}", f".{name}").group(1)

    font_m = need(r"const\s+lv_font_t\s+(\w+)\s*=\s*\{", "the lv_font_t definition")
    return ParsedFont(
        symbol=font_m.group(1), line_height=int(field_of("line_height")),
        base_line=int(field_of("base_line")), bpp=int(field_of("bpp")),
        bitmap_format=field_of("bitmap_format"), stride=int(field_of("stride")),
        cmap_num=int(field_of("cmap_num")), kern=field_of("kern_dsc", r"([&\w]+)"),
        bitmap=bitmap, glyphs=glyphs, cmaps=cmaps,
        includes_lvgl='#include "lvgl.h"' in src, generated=GENERATED_MARKER in src)


def structure_errors(pf: ParsedFont, stem: str) -> list[str]:
    """LVGL 9.5 compatibility and layout rules of spec 11.3 / amendment A2."""
    e: list[str] = []
    if pf.symbol != stem:
        e.append(f"symbol {pf.symbol} != file name {stem}")
    if not pf.generated:
        e.append("not generated by tools/vocab_fonts.py")
    if not pf.includes_lvgl:
        e.append('missing #include "lvgl.h"')
    if pf.bpp != 4 or pf.bitmap_format not in ("LV_FONT_FMT_TXT_PLAIN", "0") or pf.stride != 0:
        e.append("bitmaps must be PLAIN 4 bpp with stride 0 (uncompressed, rows unpadded)")
    if pf.kern != "NULL":
        e.append("unexpected kerning data")
    if pf.cmap_num != len(pf.cmaps) or not pf.cmaps:
        e.append(f"cmap_num {pf.cmap_num} != {len(pf.cmaps)} cmaps")
    if not pf.glyphs or pf.glyphs[0] != Glyph(0, 0, 0, 0, 0, 0):
        e.append("glyph id 0 must be the reserved all-zero descriptor")
    if pf.line_height <= 0 or not 0 <= pf.base_line < pf.line_height:
        e.append(f"invalid line_height {pf.line_height} / base_line {pf.base_line}")

    offset = 0
    for gid, g in enumerate(pf.glyphs[1:], 1):
        if g.bitmap_index != offset:
            e.append(f"glyph {gid}: bitmap_index {g.bitmap_index} != {offset} (byte-aligned, contiguous)")
            break
        offset += (g.box_w * g.box_h + 1) // 2
        if not (0 <= g.box_w <= 255 and 0 <= g.box_h <= 255 and -128 <= g.ofs_x <= 127
                and -128 <= g.ofs_y <= 127 and 0 < g.adv_w <= 4095 and g.bitmap_index < 1 << 20):
            e.append(f"glyph {gid}: descriptor field out of range")
        if g.box_h and (g.ofs_y < -pf.base_line or g.ofs_y + g.box_h > pf.line_height - pf.base_line):
            e.append(f"glyph {gid}: box leaves the line box")
    if offset != len(pf.bitmap):
        e.append(f"bitmap has {len(pf.bitmap)} bytes, descriptors need {offset}")

    first = pf.cmaps[0] if pf.cmaps else None
    if not first or (first.kind, first.range_start, first.range_length, first.glyph_id_start,
                     first.unicode_list) != (FORMAT0_TINY, 0x20, 95, 1, None):
        e.append("cmap 0 must be FORMAT0_TINY U+0020..U+007E starting at glyph 1")
    next_gid = 1
    prev_end = 0
    for i, c in enumerate(pf.cmaps):
        if c.kind not in (FORMAT0_TINY, SPARSE_TINY):
            e.append(f"cmap {i}: {c.kind} (only FORMAT0_TINY and SPARSE_TINY are allowed)")
            continue
        if c.glyph_id_start != next_gid:
            e.append(f"cmap {i}: glyph_id_start {c.glyph_id_start} != {next_gid}")
        if c.range_start < prev_end or not 0 < c.range_length <= 0xFFFF:
            e.append(f"cmap {i}: range overlaps or has an invalid length")
        prev_end = c.range_start + c.range_length
        if c.kind == FORMAT0_TINY:
            if c.unicode_list is not None or c.list_length:
                e.append(f"cmap {i}: FORMAT0_TINY must not have lists")
            next_gid += c.range_length
        else:
            ul = c.unicode_list or []
            if (not ul or ul[0] != 0 or ul != sorted(set(ul)) or c.list_length != len(ul)
                    or ul[-1] + 1 != c.range_length):
                e.append(f"cmap {i}: unicode_list must be sorted, unique, start at 0 and end the range")
            next_gid += len(ul)
    if next_gid != len(pf.glyphs):
        e.append(f"cmaps map {next_gid - 1} glyphs, descriptors define {len(pf.glyphs) - 1}")
    return e


