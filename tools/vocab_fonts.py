QUANT_LUT = [(v * 15 + 127) // 255 for v in range(256)]  # 8-bit coverage -> 4-bit level


@dataclass
class Raster:
    cp: int
    box_w: int
    box_h: int
    ofs_x: int
    ofs_y: int
    adv16: int
    rows: list[list[int]]
    canvas: bytes      # whole quantized canvas, for placement-exact verification
    origin: tuple[int, int, int, int]  # canvas width, height, pen x, baseline y


@dataclass
class RoleResult:
    role: Role
    text: str
    rasters: list[Raster]
    meta: dict[str, object] = field(default_factory=dict)


def find_source(fonts_src: Path, name: str) -> Path:
    matches = sorted(p for p in fonts_src.rglob(name) if p.is_file())
    if not matches:
        raise FontToolError(f"{name} not found under {fonts_src}")
    return matches[0]


def rasterize(font: object, cp: int, size: int) -> Raster:
    from PIL import Image, ImageDraw  # imported lazily: --check needs no Pillow

    width = height = 4 * size
    ox, oy = size, 3 * size
    im = Image.new("L", (width, height), 0)
    ImageDraw.Draw(im).text((ox, oy), chr(cp), font=font, fill=255, anchor="ls")
    q = im.point(QUANT_LUT)
    canvas = q.tobytes()
    bbox = q.getbbox()
    adv16 = int(round(font.getlength(chr(cp)) * 16))
    if bbox is None:
        return Raster(cp, 0, 0, 0, 0, adv16, [], canvas, (width, height, ox, oy))
    x0, y0, x1, y1 = bbox
    if x0 == 0 or y0 == 0 or x1 == width or y1 == height:
        raise FontToolError(f"{u_label(cp)} touches the rasterization canvas edge")
    rows = [list(canvas[y * width + x0:y * width + x1]) for y in range(y0, y1)]
    return Raster(cp, x1 - x0, y1 - y0, x0 - ox, oy - y1, adv16, rows, canvas,
                  (width, height, ox, oy))


def c_comment(text: str) -> str:
    return text.replace("*/", "* /")


def emit_c(role: Role, rasters: list[Raster], line_height: int, base_line: int,
           underline: tuple[int, int], meta: dict[str, object]) -> str:
    ascii_part = [r for r in rasters if r.cp <= 0x7E]
    rest = [r for r in rasters if r.cp > 0x7E]
    ranges: list[list[Raster]] = []
    for r in rest:
        if ranges and r.cp - ranges[-1][0].cp <= 0xFFFE:
            ranges[-1].append(r)
        else:
            ranges.append([r])
    bitmap_lines, dsc_lines = [], []
    index = 0
    for r in ascii_part + rest:
        ch = chr(r.cp)
        label = ch if r.cp > 0x20 and ch not in "\\\"" else ("space" if r.cp == 0x20 else ch)
        bitmap_lines.append(f"    /* {u_label(r.cp)} \"{c_comment(label)}\" */")
        flat = [v for row in r.rows for v in row]
        if len(flat) % 2:
            flat.append(0)
        packed = [(flat[i] << 4) | flat[i + 1] for i in range(0, len(flat), 2)]
        for i in range(0, len(packed), 12):
            bitmap_lines.append("    " + ", ".join(f"0x{b:02x}" for b in packed[i:i + 12]) + ",")
        dsc_lines.append(
            f"    {{.bitmap_index = {index}, .adv_w = {r.adv16}, .box_w = {r.box_w}, "
            f".box_h = {r.box_h}, .ofs_x = {r.ofs_x}, .ofs_y = {r.ofs_y}}},  /* {u_label(r.cp)} */")
        index += len(packed)

    out = [
        "/*******************************************************************************",
        f" * {role.symbol} - font role {role.role} of main/vocab_fonts.h.",
        f" * {GENERATED_MARKER} {TOOL_VERSION}; do not edit. Regenerate with",
        " * `tools/vocab_fonts.py generate`; verify with `python3 tools/vocab_fonts.py --check`.",
        " *",
        f" * {role.family} ({role.source}, {c_comment(str(meta['version']))},",
        f" * SHA-256 {meta['source_sha256']}) at {role.size} px,",
        f" * rasterized with Pillow {meta['pillow']} / FreeType {meta['freetype']}.",
        " * 4 bpp PLAIN, high nibble first, every glyph byte-aligned, rows unpadded;",
        f" * FORMAT0_TINY U+0020..U+007E + {len(ranges)} SPARSE_TINY; line_height {line_height},",
        f" * base_line {base_line}; no kerning; {len(rasters)} glyphs, {index} bitmap bytes.",
    ]
    if role.double_storey_a:
        out.append(" * U+0061 uses the double-storey a (OpenType ss13) so IPA a and U+0251 differ.")
    out += [
        " *",
        f" * {c_comment(str(meta['copyright']))}",
        f" * SIL Open Font License 1.1: assets/fonts/vocab/{LICENSE_OF_SOURCE[role.source]}.",
        " * This subset is a Modified Version and does not use the Reserved Font Name(s).",
        " ******************************************************************************/",
        '#include "lvgl.h"',
        "",
        "/* Glyph bitmaps (glyph id order). */",
        "static LV_ATTRIBUTE_LARGE_CONST const uint8_t glyph_bitmap[] = {",
        *bitmap_lines,
        "};",
        "",
        "/* Glyph descriptors: adv_w in 1/16 px; ofs_y = box bottom above the baseline. */",
        "static const lv_font_fmt_txt_glyph_dsc_t glyph_dsc[] = {",
        "    {.bitmap_index = 0, .adv_w = 0, .box_w = 0, .box_h = 0, .ofs_x = 0, .ofs_y = 0},  /* id 0 reserved */",
        *dsc_lines,
        "};",
        "",
    ]
    for k, rng in enumerate(ranges, 1):
        offsets = [r.cp - rng[0].cp for r in rng]
        out.append(f"static const uint16_t unicode_list_{k}[] = {{")
        for i in range(0, len(offsets), 10):
            out.append("    " + ", ".join(f"0x{v:04x}" for v in offsets[i:i + 10]) + ",")
        out += ["};", ""]
    out += [
        "static const lv_font_fmt_txt_cmap_t cmaps[] = {",
        "    {",
        "        .range_start = 32, .range_length = 95, .glyph_id_start = 1,",
        "        .unicode_list = NULL, .glyph_id_ofs_list = NULL, .list_length = 0,",
        f"        .type = {FORMAT0_TINY},",
        "    },",
    ]
    gid = 1 + len(ascii_part)
    for k, rng in enumerate(ranges, 1):
        out += [
            "    {",
            f"        .range_start = {rng[0].cp}, .range_length = {rng[-1].cp - rng[0].cp + 1}, "
            f".glyph_id_start = {gid},",
            f"        .unicode_list = unicode_list_{k}, .glyph_id_ofs_list = NULL, "
            f".list_length = {len(rng)},",
            f"        .type = {SPARSE_TINY},",
            "    },",
        ]
        gid += len(rng)
    out += [
        "};",
        "",
        "static const lv_font_fmt_txt_dsc_t font_dsc = {",
        "    .glyph_bitmap = glyph_bitmap,",
        "    .glyph_dsc = glyph_dsc,",
        "    .cmaps = cmaps,",
        "    .kern_dsc = NULL,",
        "    .kern_scale = 0,",
        f"    .cmap_num = {1 + len(ranges)},",
        "    .bpp = 4,",
        "    .kern_classes = 0,",
        "    .bitmap_format = LV_FONT_FMT_TXT_PLAIN,",
        "    .stride = 0,",
        "};",
        "",
        f"const lv_font_t {role.symbol} = {{",
        "    .get_glyph_dsc = lv_font_get_glyph_dsc_fmt_txt,",
        "    .get_glyph_bitmap = lv_font_get_bitmap_fmt_txt,",
        f"    .line_height = {line_height},",
        f"    .base_line = {base_line},",
        "    .subpx = LV_FONT_SUBPX_NONE,",
        f"    .underline_position = {underline[0]},",
        f"    .underline_thickness = {underline[1]},",
        "    .dsc = &font_dsc,",
        "    .fallback = NULL,",
        "    .user_data = NULL,",
        "};",
        "",
    ]
    return "\n".join(out)


def verify_generated(role: Role, text: str, rasters: list[Raster]) -> ParsedFont:
    """Re-parses the emitted C and compares every glyph, decoded and placed exactly as
    LVGL 9.5 does it, with the rasterization pixel by pixel."""
    pf = parse_font_c(text)
    errors = structure_errors(pf, role.symbol)
    asc = pf.line_height - pf.base_line  # baseline offset from the line top
    for r in rasters:
        gid = pf.lookup(r.cp)
        if gid == 0:
            errors.append(f"{u_label(r.cp)}: not reachable through the cmaps")
            continue
        g = pf.glyphs[gid]
        if (g.box_w, g.box_h, g.ofs_x, g.ofs_y, g.adv_w) != (r.box_w, r.box_h, r.ofs_x, r.ofs_y,
                                                                r.adv16):
            errors.append(f"{u_label(r.cp)}: descriptor differs from the rasterization")
            continue
        width, height, ox, oy = r.origin
        top = oy - asc                              # line top for a baseline at oy
        y1 = top + asc - g.box_h - g.ofs_y          # lv_draw_label.c letter placement
        x1 = ox + g.ofs_x
        canvas = bytearray(width * height)
        for y, row in enumerate(pf.decode(gid)):
            for x, v in enumerate(row):
                canvas[(y1 + y) * width + x1 + x] = v
        if bytes(canvas) != r.canvas:
            errors.append(f"{u_label(r.cp)}: decoded glyph differs from the rasterization")
    if errors:
        raise FontToolError(f"{role.symbol}: " + "; ".join(errors[:10]))
    return pf


def glyph_distance(pf: ParsedFont, a: int, b: int, pf_b: ParsedFont | None = None) -> int:
    """Pixels whose 4-bit level differs by 4 or more between glyph `a` of `pf` and glyph
    `b` of `pf_b` (default `pf`), both placed at the same pen position and baseline."""
    def canvas(font: ParsedFont, cp: int) -> dict[tuple[int, int], int]:
        gid = font.lookup(cp)
        g = font.glyphs[gid]
        return {(g.ofs_x + x, -g.ofs_y - g.box_h + y): v
                for y, row in enumerate(font.decode(gid)) for x, v in enumerate(row)}
    ca, cb = canvas(pf, a), canvas(pf_b or pf, b)
    return sum(1 for k in set(ca) | set(cb) if abs(ca.get(k, 0) - cb.get(k, 0)) >= 4)


def generate_role(role: Role, inv: Inventory, fonts_src: Path, allow_unpinned: bool,
                  versions: dict[str, str]) -> RoleResult:
    from PIL import ImageFont

    path = find_source(fonts_src, role.source)
    data = path.read_bytes()
    digest = hashlib.sha256(data).hexdigest()
    if digest != SOURCE_SHA256[role.source] and not allow_unpinned:
        raise FontToolError(f"{path}: SHA-256 {digest} is not the pinned {role.source}")
    sf = Sfnt(data, role.source)
    cmap = sf.cmap()
    codepoints = sorted(inv.required(role))
    missing = [cp for cp in codepoints if not cmap.get(cp)]
    if missing:
        raise FontToolError(f"{role.source} has no glyph for " + " ".join(map(u_label, missing)))
    alternates = {}
    font_bytes = data
    if role.double_storey_a:
        subst = sf.single_substitutions("ss13")
        alt = subst.get(cmap[0x61])
        if not alt:
            raise FontToolError(f"{role.source}: no ss13 double-storey a")
        mapping = {cp: cmap[cp] for cp in codepoints}
        mapping[0x61] = alt
        font_bytes = sf.with_cmap(mapping)
        alternates["U+0061"] = f"double-storey a (ss13, glyph {alt}; default glyph {cmap[0x61]})"
    font = ImageFont.truetype(io.BytesIO(font_bytes), role.size,
                              layout_engine=ImageFont.Layout.BASIC)
    rasters = [rasterize(font, cp, role.size) for cp in codepoints]
    inked = [r for r in rasters if r.box_h]
    ascent = max(r.ofs_y + r.box_h for r in inked)
    descent = max(0, max(-r.ofs_y for r in inked))
    upem = sf.units_per_em()
    pos, thick = sf.underline()
    underline = (int(round(pos * role.size / upem)), max(1, int(round(thick * role.size / upem))))
    meta = {
        "source_sha256": digest,
        "version": sf.name_string(5) or "?",
        "copyright": sf.name_string(0) or "?",
        "family_name": f"{sf.name_string(1)} {sf.name_string(2)}",
        "pillow": versions["pillow"],
        "freetype": versions["freetype"],
        "alternates": alternates,
        "underline": underline,
    }
    text = emit_c(role, rasters, ascent + descent, descent, underline, meta)
    pf = verify_generated(role, text, rasters)
    if role.double_storey_a:
        distance = glyph_distance(pf, 0x61, 0x251)
        if distance < 8:
            raise FontToolError(f"{role.symbol}: U+0061 and U+0251 differ in only {distance} pixels")
        meta["a_vs_alpha_pixels"] = distance
    meta["parsed"] = pf
    return RoleResult(role, text, rasters, meta)


def write_preview(results: list[RoleResult], path: Path) -> None:
    """PNG of every role's glyphs decoded from the generated C (visual review only)."""
    from PIL import Image

    rows = []
    for res in results:
        pf: ParsedFont = res.meta["parsed"]
        per_line = 24
        cell_w = max(1, max(g.adv_w for g in pf.glyphs) // 16 + 2)
        cps = [r.cp for r in res.rasters]
        n_lines = (len(cps) + per_line - 1) // per_line
        img = Image.new("L", (cell_w * per_line + 4, pf.line_height * n_lines + 4), 0)
        for i, cp in enumerate(cps):
            gid = pf.lookup(cp)
            g = pf.glyphs[gid]
            bx = 2 + (i % per_line) * cell_w + g.ofs_x
            by = 2 + (i // per_line) * pf.line_height + (pf.line_height - pf.base_line) - g.box_h - g.ofs_y
            for y, row in enumerate(pf.decode(gid)):
                for x, v in enumerate(row):
                    if v and 0 <= bx + x < img.width and 0 <= by + y < img.height:
                        img.putpixel((bx + x, by + y), v * 17)
        rows.append(img)
    sheet = Image.new("L", (max(r.width for r in rows), sum(r.height + 6 for r in rows)), 40)
    y = 0
    for img in rows:
        sheet.paste(img, (0, y))
        y += img.height + 6
    path.parent.mkdir(parents=True, exist_ok=True)
    sheet.save(path)


def generate(fonts_src: Path, allow_unpinned: bool, preview: Path | None) -> int:
    try:
        import PIL
        from PIL import features
    except ImportError as exc:
        raise FontToolError("Pillow is required for generate (pip install pillow)") from exc
    versions = {"pillow": PIL.__version__, "freetype": str(features.version("freetype2"))}
    sources = source_files()
    inv = build_inventory(sources)
    if inv.errors:
        raise FontToolError("inventory errors: " + "; ".join(inv.errors))

    results = [generate_role(role, inv, fonts_src, allow_unpinned, versions) for role in ROLES]
    shapes = shape_errors({res.role.symbol: res.meta["parsed"] for res in results})
    if shapes:
        raise FontToolError("; ".join(shapes))

    license_hashes = {}
    for name, (src_name, digest) in LICENSES.items():
        text = norm_text(find_source(fonts_src, src_name).read_text(encoding="utf-8"))
        actual = hashlib.sha256(text.encode("utf-8")).hexdigest()
        if actual != digest and not allow_unpinned:
            raise FontToolError(f"{src_name}: SHA-256 {actual} is not the pinned license text")
        license_hashes[name] = actual
        (FONT_DIR / name).write_text(text, encoding="utf-8", newline="\n")

    fonts_json = {}
    total = 0
    for res in results:
        pf: ParsedFont = res.meta["parsed"]
        role = res.role
        path = FONT_DIR / f"{role.symbol}.c"
        path.write_text(res.text, encoding="utf-8", newline="\n")
        cps = sorted(pf.coverage())
        total += pf.flash_bytes()
        entry = {
            "role": role.role,
            "source": role.source,
            "source_family": res.meta["family_name"],
            "source_version": res.meta["version"],
            "source_sha256": res.meta["source_sha256"],
            "copyright": res.meta["copyright"],
            "license_file": f"assets/fonts/vocab/{LICENSE_OF_SOURCE[role.source]}",
            "size_px": role.size,
            "bpp": 4,
            "line_height": pf.line_height,
            "base_line": pf.base_line,
            "underline": list(res.meta["underline"]),
            "glyphs": len(pf.glyphs) - 1,
            "bitmap_bytes": len(pf.bitmap),
            "flash_estimate_bytes": pf.flash_bytes(),
            "cmaps": [f"{'FORMAT0_TINY' if c.kind == FORMAT0_TINY else 'SPARSE_TINY'} "
                      f"{u_label(c.range_start)}..{u_label(c.range_start + c.range_length - 1)} "
                      f"({c.list_length or c.range_length} code points)" for c in pf.cmaps],
            "alternates": res.meta["alternates"],
            "codepoints": " ".join(u_label(cp) for cp in cps),
            "chars": "".join(chr(cp) for cp in cps),
            "c_sha256": text_sha256(res.text),
        }
        if "a_vs_alpha_pixels" in res.meta:
            entry["a_vs_alpha_pixels"] = res.meta["a_vs_alpha_pixels"]
        fonts_json[role.symbol] = entry

    def chars_of(cps: set[int]) -> str:
        return "".join(chr(cp) for cp in sorted(cps) if cp > 0x7E)

    inventory = {
        "generator": f"tools/vocab_fonts.py {TOOL_VERSION}",
        "generate_command": "PYTHONPATH=<dir with Pillow> python3 tools/vocab_fonts.py generate "
                            "--fonts-src <dir with the pinned source fonts>",
        "check_command": "python3 tools/vocab_fonts.py --check",
        "rasterizer": {
            "pillow": versions["pillow"],
            "freetype": versions["freetype"],
            "python": sys.version.split()[0],
            "method": "ImageDraw.text(anchor='ls'), BASIC layout, FreeType default hinting; "
                      "4-bit level = round(coverage * 15 / 255); tight ink boxes",
        },
        "format": "LVGL 9.5 fmt_txt: PLAIN 4 bpp, high nibble first, byte-aligned glyphs, rows "
                  "unpadded (stride 0), FORMAT0_TINY U+0020..U+007E + SPARSE_TINY, no kerning, "
                  "line_height/base_line = ink extents of the subset",
        "inventory_sources": "string literals of main/main.c and main/vocab_*.{c,h} (comments "
                             "excluded), bank zh/ipa/English fields of main/vocab_bank.c, spec 13 "
                             "extras, amendment A5 IPA set",
        "inventory": {
            "cjk_role_non_ascii": chars_of(inv.groups["cjk"]),
            "ipa_role_non_ascii": chars_of(inv.groups["ipa"]),
            "lvgl_symbols": " ".join(u_label(cp) for cp in sorted(inv.symbols)),
            "bank_entries": inv.bank_entries,
        },
        "licenses": license_hashes,
        "fonts": fonts_json,
        "flash_estimate_total_bytes": total,
    }
    INVENTORY_PATH.write_text(json.dumps(inventory, ensure_ascii=False, indent=2) + "\n",
                              encoding="utf-8", newline="\n")
    if preview is not None:
        write_preview(results, preview)
    for res in results:
        pf = res.meta["parsed"]
        print(f"{res.role.symbol}: {len(pf.glyphs) - 1} glyphs, line_height {pf.line_height}, "
              f"base_line {pf.base_line}, {len(pf.bitmap)} bitmap bytes, about "
              f"{pf.flash_bytes()} bytes of flash")
    print(f"vocab_fonts.py generate: {len(results)} fonts verified pixel by pixel, about {total} bytes "
          f"({total / 1024:.1f} KiB) of flash")
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Word Buddy font subsets (spec 11.3, 13).")
    parser.add_argument("mode", nargs="?", choices=("generate",), help="generate the fonts")
    parser.add_argument("--check", action="store_true", help="coverage/structure check (stdlib)")
    parser.add_argument("--fonts-src", type=Path, help="directory with the pinned source fonts")
    parser.add_argument("--allow-unpinned", action="store_true",
                        help="accept source fonts/licenses whose SHA-256 differs from the pins")
    parser.add_argument("--preview", type=Path, help="write a PNG of the decoded glyphs")
    args = parser.parse_args(argv)
    if args.check == (args.mode == "generate"):
        parser.error("choose exactly one of: generate, --check")
    try:
        if args.check:
            return run_check()
        if args.fonts_src is None or not args.fonts_src.is_dir():
            parser.error("generate needs --fonts-src <directory with the source fonts>")
        return generate(args.fonts_src, args.allow_unpinned, args.preview)
    except FontToolError as exc:
        print(f"vocab_fonts.py: ERROR: {exc}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
