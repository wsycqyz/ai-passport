@dataclass
class Inventory:
    groups: dict[str, set[int]]
    origins: dict[int, set[str]]
    symbols: set[int]
    errors: list[str]
    bank_entries: int

    def required(self, role: Role) -> set[int]:
        out: set[int] = set()
        for g in role.groups:
            out |= self.groups[g]
        return out

    def origin(self, cp: int) -> str:
        return ", ".join(sorted(self.origins.get(cp, {"?"})))


def source_files(root: Path = ROOT) -> dict[str, str]:
    """main/main.c and main/vocab_*.{c,h} (the baseline demo sources are not firmware)."""
    main = root / "main"
    paths = [main / "main.c"] + sorted(main.glob("vocab_*.c")) + sorted(main.glob("vocab_*.h"))
    out = {}
    for p in paths:
        if not p.is_file():
            continue
        rel = p.relative_to(root).as_posix()
        try:
            out[rel] = p.read_bytes().decode("utf-8")
        except UnicodeDecodeError as exc:
            raise FontToolError(f"{rel} is not UTF-8: {exc}") from exc
    return out


def build_inventory(sources: dict[str, str],
                    extra_bank: tuple[dict[str, object], ...] = ()) -> Inventory:
    groups = {"ascii": set(ASCII), "cjk": set(ZH_EXTRAS), "ipa": set(IPA_EXTRAS)}
    origins: dict[int, set[str]] = {}
    for cp in ZH_EXTRAS:
        origins.setdefault(cp, set()).add("spec 13 extras")
    for cp in IPA_EXTRAS:
        origins.setdefault(cp, set()).add("amendment A5 IPA set")
    symbols: set[int] = set()
    errors: list[str] = []
    bank: list[dict[str, object]] = []

    for path in sorted(sources):
        try:
            code = normalize_c(sources[path])
            spans: list[tuple[int, int]] = []
            if path == BANK_FILE:
                entries, spans = parse_bank(code)
                bank += entries
            literals = scan_literals(code)
        except (FontToolError, IndexError, KeyError, ValueError) as exc:
            errors.append(f"{path}: {exc}")
            continue
        for offset, value in literals:
            if any(start <= offset < end for start, end in spans):
                continue  # bank fields are classified below
            for ch in value:
                cp = ord(ch)
                if cp < 0x20 or 0x7F <= cp < 0xA0:
                    continue  # control characters are never drawn as glyphs
                if cp <= 0x7E:
                    continue
                if 0xE000 <= cp <= 0xF8FF:
                    symbols.add(cp)
                    if cp not in SYM_COVERAGE:
                        errors.append(f"{path}: LVGL symbol {u_label(cp)} is not in Montserrat 14 (F_SYM)")
                    continue
                groups["cjk"].add(cp)
                origins.setdefault(cp, set()).add(path)

    bank += list(extra_bank)
    if not bank:
        errors.append(f"{BANK_FILE}: no bank entries found")
    for entry in bank:
        uid = entry.get("uid")
        for fld in ("text", "example", "example_cloze", "cloze_right", "cloze_wrong"):
            value = entry.get(fld)
            if value is None:
                continue
            bad = sorted({ord(c) for c in str(value) if not 0x20 <= ord(c) <= 0x7E})
            if bad:
                errors.append(f"bank uid {uid} {fld}: {' '.join(map(u_label, bad))} not printable "
                              "ASCII (the Andika word roles carry printable ASCII only)")
        for fld, group in (("zh", "cjk"), ("example_zh", "cjk"), ("ipa", "ipa")):
            value = entry.get(fld)
            if value is None:
                continue
            for ch in str(value):
                cp = ord(ch)
                if cp < 0x20 or 0x7F <= cp < 0xA0:
                    errors.append(f"bank uid {uid} {fld}: control character {u_label(cp)}")
                elif cp > 0x7E:
                    groups[group].add(cp)
                    origins.setdefault(cp, set()).add(f"bank {fld}")
    return Inventory(groups, origins, symbols, errors, len(bank))


