def _u16(b: bytes, o: int) -> int:
    return struct.unpack_from(">H", b, o)[0]


def _s16(b: bytes, o: int) -> int:
    return struct.unpack_from(">h", b, o)[0]


def _u32(b: bytes, o: int) -> int:
    return struct.unpack_from(">I", b, o)[0]


class Sfnt:
    def __init__(self, data: bytes, name: str):
        self.data = data
        self.name = name
        if data[:4] == b"ttcf":
            raise FontToolError(f"{name}: font collections are not supported")
        self.records: dict[str, int] = {}
        for i in range(_u16(data, 4)):
            rec = 12 + 16 * i
            self.records[data[rec:rec + 4].decode("latin-1")] = rec

    def table(self, tag: str) -> bytes:
        rec = self.records.get(tag)
        if rec is None:
            raise FontToolError(f"{self.name}: no '{tag}' table")
        off, length = _u32(self.data, rec + 8), _u32(self.data, rec + 12)
        return self.data[off:off + length]

    def cmap(self) -> dict[int, int]:
        """Unicode code point -> glyph id (format 12 preferred, else format 4)."""
        t = self.table("cmap")
        subs = {}
        for i in range(_u16(t, 2)):
            pid, eid, off = _u16(t, 4 + 8 * i), _u16(t, 6 + 8 * i), _u32(t, 8 + 8 * i)
            subs[(pid, eid, _u16(t, off))] = off
        for key in ((3, 10, 12), (0, 4, 12), (0, 6, 12), (3, 1, 4), (0, 3, 4), (0, 4, 4)):
            if key in subs:
                return self._cmap12(t, subs[key]) if key[2] == 12 else self._cmap4(t, subs[key])
        raise FontToolError(f"{self.name}: no Unicode cmap")

    @staticmethod
    def _cmap12(t: bytes, off: int) -> dict[int, int]:
        out = {}
        for i in range(_u32(t, off + 12)):
            start, end, gid = struct.unpack_from(">III", t, off + 16 + 12 * i)
            for cp in range(start, end + 1):
                out[cp] = gid + cp - start
        return out

    @staticmethod
    def _cmap4(t: bytes, off: int) -> dict[int, int]:
        out = {}
        seg = _u16(t, off + 6) // 2
        ends, starts = off + 14, off + 16 + 2 * seg
        deltas, ranges = starts + 2 * seg, starts + 4 * seg
        for i in range(seg):
            end, start = _u16(t, ends + 2 * i), _u16(t, starts + 2 * i)
            delta, ro = _u16(t, deltas + 2 * i), _u16(t, ranges + 2 * i)
            for cp in range(start, end + 1):
                if cp == 0xFFFF:
                    continue
                if ro == 0:
                    gid = (cp + delta) & 0xFFFF
                else:
                    gid = _u16(t, ranges + 2 * i + ro + 2 * (cp - start))
                    gid = (gid + delta) & 0xFFFF if gid else 0
                if gid:
                    out[cp] = gid
        return out

    def name_string(self, name_id: int) -> str | None:
        t = self.table("name")
        count, strings = _u16(t, 2), _u16(t, 4)
        found = {}
        for i in range(count):
            pid, eid, lang, nid, length, off = struct.unpack_from(">HHHHHH", t, 6 + 12 * i)
            if nid != name_id:
                continue
            raw = t[strings + off:strings + off + length]
            if pid == 3 and eid in (0, 1, 10):
                found[(0, lang != 0x409)] = raw.decode("utf-16-be", "replace")
            elif pid == 1 and eid == 0:
                found[(1, lang != 0)] = raw.decode("mac_roman", "replace")
        return found[min(found)] if found else None

    def units_per_em(self) -> int:
        return _u16(self.table("head"), 18)

    def underline(self) -> tuple[int, int]:
        post = self.table("post")
        return _s16(post, 8), _s16(post, 10)

    def single_substitutions(self, feature: str) -> dict[int, int]:
        """glyph -> glyph of every GSUB single substitution (incl. extension) of `feature`."""
        g = self.table("GSUB")
        flist, llist = _u16(g, 6), _u16(g, 8)
        lookups: set[int] = set()
        for i in range(_u16(g, flist)):
            rec = flist + 2 + 6 * i
            if g[rec:rec + 4].decode("latin-1") == feature:
                ft = flist + _u16(g, rec + 4)
                lookups.update(_u16(g, ft + 4 + 2 * k) for k in range(_u16(g, ft + 2)))
        out: dict[int, int] = {}
        for index in sorted(lookups):
            lk = llist + _u16(g, llist + 2 + 2 * index)
            kind = _u16(g, lk)
            for s in range(_u16(g, lk + 4)):
                sub, sub_kind = lk + _u16(g, lk + 6 + 2 * s), kind
                if sub_kind == 7:  # extension subtable
                    sub_kind, sub = _u16(g, sub + 2), sub + _u32(g, sub + 4)
                if sub_kind != 1:
                    continue
                fmt, coverage = _u16(g, sub), self._coverage(g, sub + _u16(g, sub + 2))
                for k, glyph in enumerate(coverage):
                    if fmt == 1:
                        out[glyph] = (glyph + _s16(g, sub + 4)) & 0xFFFF
                    elif fmt == 2:
                        out[glyph] = _u16(g, sub + 6 + 2 * k)
        return out

    @staticmethod
    def _coverage(g: bytes, off: int) -> list[int]:
        fmt, count = _u16(g, off), _u16(g, off + 2)
        if fmt == 1:
            return [_u16(g, off + 4 + 2 * i) for i in range(count)]
        glyphs = []
        for i in range(count):
            start, end, _ = struct.unpack_from(">HHH", g, off + 4 + 6 * i)
            glyphs.extend(range(start, end + 1))
        return glyphs

    def with_cmap(self, mapping: dict[int, int]) -> bytes:
        """The font with its cmap replaced by one (3,10) format 12 subtable of `mapping`."""
        groups: list[list[int]] = []
        for cp, gid in sorted(mapping.items()):
            if groups and cp == groups[-1][1] + 1 and gid == groups[-1][2] + (cp - groups[-1][0]):
                groups[-1][1] = cp
            else:
                groups.append([cp, cp, gid])
        sub = struct.pack(">HHIII", 12, 0, 16 + 12 * len(groups), 0, len(groups))
        sub += b"".join(struct.pack(">III", *grp) for grp in groups)
        table = struct.pack(">HHHHI", 0, 1, 3, 10, 12) + sub
        data = bytearray(self.data)
        while len(data) % 4:
            data.append(0)
        offset = len(data)
        padded = table + b"\0" * (-len(table) % 4)
        data += padded
        checksum = sum(struct.unpack(f">{len(padded) // 4}I", padded)) & 0xFFFFFFFF
        struct.pack_into(">III", data, self.records["cmap"] + 4, checksum, offset, len(table))
        return bytes(data)


